"""
eval_behavior.py -- STEP 1 behavior check: ask a VLM what time each clock shows.

Loads a VLM in float16 (any model with an adapter -- see adapters.py; Qwen2.5-VL-3B
by default), shows it each clock image generated by clocks.py, asks it to read
the time, and logs every answer (parsed and raw) to a results CSV. This
script does NOT do any interpretability -- it only records model behavior
for later analysis (analyze.py).

Usage as a script:
    python eval_behavior.py --data_csv data/data.csv --images_dir data
    python eval_behavior.py --model_id Qwen/Qwen2.5-VL-7B-Instruct --data_csv data/data.csv --images_dir data
    # writes to results/<model_short_name>/results.csv by default (see adapters.output_dir_for)

Usage as a library (e.g. from the notebook):
    from eval_behavior import run_eval
    results_df = run_eval(data_csv="data/data.csv", images_dir="data")
"""

import argparse
import os
import re

import pandas as pd
from tqdm import tqdm

PROMPT = "What time does this clock show? Answer only in HH:MM format."
MODEL_ID = "Qwen/Qwen2.5-VL-3B-Instruct"   # this project's original model -- see adapters.py for others
SEED = 0

# Matches things like "3:45", "03:45", "12:05" anywhere in the model's reply.
TIME_RE = re.compile(r"(\d{1,2}):(\d{2})")


def parse_time_answer(text):
    """Extract (hour, minute) ints from a model reply string.

    Returns (hour, minute, success). success=False (hour/minute=None) if no
    HH:MM pattern was found, or if the numbers are out of a valid clock range.
    """
    match = TIME_RE.search(text)
    if not match:
        return None, None, False

    hour, minute = int(match.group(1)), int(match.group(2))

    # Sanity-check the range. Models sometimes output 24h-style hours (e.g.
    # "13:45") or garbage; treat those as parse failures too since our
    # ground truth is always a 12-hour analog reading (hour in 1-12).
    if not (0 <= hour <= 23) or not (0 <= minute <= 59):
        return None, None, False
    hour_12 = hour if 1 <= hour <= 12 else (hour - 12 if hour > 12 else 12)

    return hour_12, minute, True


# load_model / ask_model: these used to be defined here, hardcoded to
# Qwen2.5-VL. Model loading and asking a single image are now behind
# adapters.py's ModelAdapter interface (adapter.load() / adapter.build_inputs()
# / adapter.generate_answer()) -- see adapters.py's module docstring for why
# (replicating this behavior check on Gemma 3 / InternVL3 means writing an
# adapter once, not editing every script that asks a model something).


def run_eval(
    data_csv="data/data.csv",
    images_dir="data",
    out_csv=None,
    model_id=None,
    adapter_name=None,
    max_new_tokens=16,
    max_images=None,
    seed=SEED,
):
    """Run the behavior check over every clock in `data_csv` and save results.

    Generation is deterministic: `do_sample=False` (greedy decoding, inside
    each adapter's `generate_answer`), plus a fixed seed set here for full
    reproducibility (greedy decoding shouldn't need one, but this also pins
    any other randomness, e.g. in kernel selection). `max_new_tokens` is kept
    small since the expected answer is just "HH:MM".

    `out_csv=None` (the default) writes to results/<model_short_name>/results.csv
    (see adapters.output_dir_for) so different models never overwrite each
    other's results; pass an explicit path to override.

    Writes:
      - out_csv: one row per image with the true time, the model's raw text
        reply, the parsed prediction, and a parse_success flag.
      - <out_csv dir>/parse_failures.csv: just the rows that failed to parse,
        for quick inspection.

    Returns the results DataFrame.
    """
    from transformers import set_seed
    from adapters import get_adapter, output_dir_for
    set_seed(seed)

    df = pd.read_csv(data_csv)
    if max_images is not None:
        df = df.head(max_images)

    adapter = get_adapter(model_id=model_id, adapter_name=adapter_name)
    adapter.load(model_id)

    if out_csv is None:
        out_csv = os.path.join(output_dir_for("results", adapter), "results.csv")

    rows = []
    for _, row in tqdm(df.iterrows(), total=len(df), desc="Evaluating clocks"):
        image_path = os.path.join(images_dir, row["filename"])
        inputs = adapter.build_inputs(image_path, PROMPT)
        raw_reply = adapter.generate_answer(inputs, max_new_tokens=max_new_tokens)
        pred_hour, pred_minute, ok = parse_time_answer(raw_reply)

        rows.append({
            "filename": row["filename"],
            "true_hour": row["hour"],
            "true_minute": row["minute"],
            "raw_answer": raw_reply,
            "pred_hour": pred_hour,
            "pred_minute": pred_minute,
            "parse_success": ok,
        })

    results_df = pd.DataFrame(rows)

    out_dir = os.path.dirname(out_csv) or "."
    os.makedirs(out_dir, exist_ok=True)
    results_df.to_csv(out_csv, index=False)

    failures = results_df[~results_df["parse_success"]]
    failures_path = os.path.join(out_dir, "parse_failures.csv")
    failures.to_csv(failures_path, index=False)

    n_fail = len(failures)
    print(f"Done. {len(results_df)} images evaluated, {n_fail} parse failures "
          f"({n_fail / len(results_df):.1%}).")
    print(f"Results saved to '{out_csv}', parse failures to '{failures_path}'.")

    return results_df


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Evaluate a VLM's clock-reading behavior.")
    parser.add_argument("--data_csv", type=str, default="data/data.csv",
                         help="CSV of clock metadata produced by clocks.py")
    parser.add_argument("--images_dir", type=str, default="data",
                         help="directory containing the clock PNGs")
    parser.add_argument("--out_csv", type=str, default=None,
                         help="where to write the results CSV (default: "
                              "results/<model_short_name>/results.csv -- see adapters.output_dir_for)")
    parser.add_argument("--model_id", type=str, default=None,
                         help="Hugging Face model id. Default: the resolved adapter's own default "
                              "(Qwen2.5-VL-3B if neither --model_id nor --adapter is given).")
    parser.add_argument("--adapter", type=str, default=None,
                         help="which model-family adapter to use (see adapters.py) -- inferred from "
                              "--model_id if omitted.")
    parser.add_argument("--max_new_tokens", type=int, default=16)
    parser.add_argument("--max_images", type=int, default=None,
                         help="only evaluate the first N images (useful for a quick test run)")
    parser.add_argument("--seed", type=int, default=SEED, help="random seed for reproducibility")
    args = parser.parse_args()

    run_eval(
        data_csv=args.data_csv,
        images_dir=args.images_dir,
        out_csv=args.out_csv,
        model_id=args.model_id,
        adapter_name=args.adapter,
        max_new_tokens=args.max_new_tokens,
        max_images=args.max_images,
        seed=args.seed,
    )
